/**
 * DockerHardener — adds a production-minded Dockerfile when missing.
 */

import { promises as fs } from 'node:fs'
import path from 'node:path'
import type {
  Hardener,
  HardenerFindings,
  ChangePlan,
  ApplyContext,
  ApplyResult,
  ValidationResult,
  FileChange,
} from '../types/hardener.js'
import type { ProjectModel } from '../types/project-model.js'

function buildNodeDockerfile(model: ProjectModel): string {
  const usePnpm = model.packageManagers.includes('pnpm')
  const useYarn = model.packageManagers.includes('yarn')

  let installCmd = 'npm ci'
  let lockCopy = 'COPY package.json package-lock.json* ./'
  if (usePnpm) {
    installCmd = 'corepack enable && pnpm install --frozen-lockfile'
    lockCopy = 'COPY package.json pnpm-lock.yaml ./'
  } else if (useYarn) {
    installCmd = 'yarn install --frozen-lockfile'
    lockCopy = 'COPY package.json yarn.lock ./'
  }

  return `# syntax=docker/dockerfile:1
# Generated by RepoForge — review before production use

FROM node:20-alpine AS deps
WORKDIR /app
${lockCopy}
RUN ${installCmd}

FROM node:20-alpine AS build
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
RUN npm run build --if-present

FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production
RUN addgroup -g 1001 -S nodejs && adduser -S app -u 1001
COPY --from=build /app ./
USER app
EXPOSE 3000
CMD ["npm", "start"]
`
}

function buildPythonDockerfile(): string {
  return `# syntax=docker/dockerfile:1
# Generated by RepoForge — review before production use

FROM python:3.12-slim AS base
WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1
ENV PYTHONUNBUFFERED=1

RUN adduser --disabled-password --gecos "" app

COPY requirements.txt* pyproject.toml* ./
RUN pip install --no-cache-dir -r requirements.txt 2>/dev/null || pip install --no-cache-dir .

COPY . .
USER app
EXPOSE 8000
CMD ["python", "-m", "uvicorn", "main:app", "--host", "0.0.0.0", "--port", "8000"]
`
}

function buildGenericDockerfile(): string {
  return `# syntax=docker/dockerfile:1
# Generated by RepoForge — replace with a language-specific image

FROM alpine:3.20
WORKDIR /app
COPY . .
CMD ["echo", "Configure a proper CMD for your application"]
`
}

export class DockerHardener implements Hardener {
  readonly name = 'docker'
  readonly description = 'Adds a multi-stage Dockerfile when none exists'

  supports(project: ProjectModel): boolean {
    return !project.hasDocker && project.languages.length > 0
  }

  async analyze(project: ProjectModel): Promise<HardenerFindings> {
    return {
      summary: project.hasDocker
        ? 'Dockerfile present'
        : 'No Dockerfile detected',
      details: {
        hasDocker: project.hasDocker,
        hasDockerCompose: project.hasDockerCompose,
        languages: project.languages,
      },
      addressableIssueIds: project.hasDocker ? [] : ['no-docker'],
    }
  }

  async plan(project: ProjectModel, _findings: HardenerFindings): Promise<ChangePlan> {
    if (project.hasDocker) {
      return {
        hardenerName: this.name,
        description: 'Dockerfile already exists',
        changes: [],
        risk: 'low',
        requiresConfirmation: false,
      }
    }

    let content: string
    if (
      project.packageManagers.some((p) =>
        ['npm', 'pnpm', 'yarn', 'bun'].includes(p)
      ) ||
      project.languages.includes('typescript') ||
      project.languages.includes('javascript')
    ) {
      content = buildNodeDockerfile(project)
    } else if (project.languages.includes('python')) {
      content = buildPythonDockerfile()
    } else {
      content = buildGenericDockerfile()
    }

    const changes: FileChange[] = [
      {
        path: 'Dockerfile',
        content,
        reason: 'Add multi-stage Dockerfile for reproducible builds',
      },
    ]

    return {
      hardenerName: this.name,
      description: 'Add production-oriented Dockerfile',
      changes,
      risk: 'low',
      requiresConfirmation: false,
    }
  }

  async apply(ctx: ApplyContext): Promise<ApplyResult> {
    const applied: FileChange[] = []
    const skipped: FileChange[] = []
    const errors: string[] = []
    const logs: string[] = []

    for (const change of ctx.plan.changes) {
      if (!change.content) {
        skipped.push(change)
        continue
      }

      const target = path.join(ctx.workDir, change.path)

      if (ctx.dryRun) {
        logs.push(`[dry-run] would write ${change.path}`)
        applied.push(change)
        continue
      }

      try {
        try {
          await fs.access(target)
          logs.push(`skip ${change.path}: already exists`)
          skipped.push(change)
          continue
        } catch {
          // ok
        }

        await fs.writeFile(target, change.content, 'utf8')
        logs.push(`wrote ${change.path}`)
        applied.push(change)
      } catch (err) {
        const msg = err instanceof Error ? err.message : String(err)
        errors.push(`${change.path}: ${msg}`)
      }
    }

    return {
      hardenerName: this.name,
      success: errors.length === 0,
      appliedChanges: applied,
      skippedChanges: skipped,
      errors,
      logs,
    }
  }

  async validate(result: ApplyResult, ctx: ApplyContext): Promise<ValidationResult> {
    const errors: string[] = []
    const warnings: string[] = []

    if (!result.success) errors.push(...result.errors)

    for (const change of result.appliedChanges) {
      if (ctx.dryRun) continue
      const target = path.join(ctx.workDir, change.path)
      try {
        const content = await fs.readFile(target, 'utf8')
        if (!content.includes('FROM ')) {
          errors.push(`${change.path} does not look like a valid Dockerfile`)
        }
        if (!content.includes('USER ') && content.includes('node:')) {
          warnings.push(`${change.path}: consider running as non-root (USER directive)`)
        }
      } catch {
        errors.push(`${change.path} missing after apply`)
      }
    }

    return { ok: errors.length === 0, errors, warnings }
  }
}
