/**
 * SecurityHardener — baseline security posture for a repository.
 */

import { promises as fs } from 'node:fs'
import path from 'node:path'
import type {
  Hardener,
  HardenerFindings,
  ChangePlan,
  ApplyContext,
  ApplyResult,
  ValidationResult,
  FileChange,
} from '../types/hardener.js'
import type { ProjectModel } from '../types/project-model.js'

function buildDependabot(model: ProjectModel): string {
  const ecosystems: string[] = []
  if (model.packageManagers.some((p) => ['npm', 'pnpm', 'yarn', 'bun'].includes(p))) {
    ecosystems.push('npm')
  }
  if (model.packageManagers.includes('pip') || model.languages.includes('python')) {
    ecosystems.push('pip')
  }
  if (model.packageManagers.includes('go') || model.languages.includes('go')) {
    ecosystems.push('gomod')
  }
  if (model.packageManagers.includes('cargo') || model.languages.includes('rust')) {
    ecosystems.push('cargo')
  }
  if (ecosystems.length === 0) ecosystems.push('npm')

  const updates = ecosystems
    .map(
      (eco) => `  - package-ecosystem: "${eco}"
    directory: "/"
    schedule:
      interval: "weekly"
    open-pull-requests-limit: 10`
    )
    .join('\n')

  return `# Generated by RepoForge
version: 2
updates:
${updates}
`
}

function buildGitignoreAdditions(): string {
  return `
# --- RepoForge security baseline ---
.env
.env.*
!.env.example
*.pem
*.key
id_rsa
id_ed25519
credentials.json
secrets.json
service-account*.json
.aws/credentials
`
}

function buildSecurityMd(): string {
  return `# Security Policy

## Supported Versions

| Version | Supported          |
| ------- | ------------------ |
| main    | :white_check_mark: |

## Reporting a Vulnerability

Please report security issues privately.

- Prefer GitHub Security Advisories, or
- Contact the maintainers directly.

Do **not** open public issues for vulnerabilities.

We aim to acknowledge reports within 72 hours.
`
}

export class SecurityHardener implements Hardener {
  readonly name = 'security'
  readonly description =
    'Adds Dependabot, SECURITY.md and strengthens .gitignore against common secret leaks'

  supports(_project: ProjectModel): boolean {
    return true
  }

  async analyze(project: ProjectModel): Promise<HardenerFindings> {
    const missing: string[] = []
    if (!project.security.hasDependabot) missing.push('dependabot')
    if (!project.security.hasSecurityMd) missing.push('SECURITY.md')
    missing.push('gitignore-secrets')

    const coreMissing = missing.filter((m) => m !== 'gitignore-secrets')
    return {
      summary:
        coreMissing.length > 0
          ? `Security gaps: ${coreMissing.join(', ')}`
          : 'Core security files present — checking .gitignore baseline',
      details: {
        hasDependabot: project.security.hasDependabot,
        hasSecurityMd: project.security.hasSecurityMd,
        hasSecretsInCode: project.security.hasSecretsInCode,
        missing,
      },
      addressableIssueIds: project.issues
        .filter((i) => i.category === 'security' || i.id === 'no-dependabot')
        .map((i) => i.id),
    }
  }

  async plan(project: ProjectModel, findings: HardenerFindings): Promise<ChangePlan> {
    const missing = (findings.details.missing as string[]) ?? []
    const changes: FileChange[] = []

    if (missing.includes('dependabot') && !project.security.hasDependabot) {
      changes.push({
        path: '.github/dependabot.yml',
        content: buildDependabot(project),
        reason: 'Enable automated dependency updates via Dependabot',
      })
    }

    if (missing.includes('SECURITY.md') && !project.security.hasSecurityMd) {
      changes.push({
        path: 'SECURITY.md',
        content: buildSecurityMd(),
        reason: 'Add security policy for responsible disclosure',
      })
    }

    let needsGitignore = true
    try {
      const existing = await fs.readFile(path.join(project.rootDir, '.gitignore'), 'utf8')
      if (existing.includes('RepoForge security baseline')) {
        needsGitignore = false
      }
    } catch {
      // missing file
    }
    if (needsGitignore) {
      changes.push({
        path: '.gitignore',
        content: '',
        reason: 'Strengthen .gitignore against common secret and credential patterns',
      })
    }

    return {
      hardenerName: this.name,
      description:
        changes.length === 0
          ? 'Security baseline already satisfied'
          : 'Apply security baseline (Dependabot, SECURITY.md, .gitignore)',
      changes,
      risk: 'low',
      requiresConfirmation: false,
    }
  }

  async apply(ctx: ApplyContext): Promise<ApplyResult> {
    const applied: FileChange[] = []
    const skipped: FileChange[] = []
    const errors: string[] = []
    const logs: string[] = []

    for (const change of ctx.plan.changes) {
      const target = path.join(ctx.workDir, change.path)

      if (change.path === '.gitignore') {
        if (ctx.dryRun) {
          logs.push('[dry-run] would strengthen .gitignore with secret patterns')
          applied.push({ ...change, content: buildGitignoreAdditions() })
          continue
        }
        try {
          let existing = ''
          try {
            existing = await fs.readFile(target, 'utf8')
          } catch {
            // create new
          }
          const addition = buildGitignoreAdditions()
          if (existing.includes('RepoForge security baseline')) {
            logs.push('skip .gitignore: security baseline already present')
            skipped.push(change)
            continue
          }
          const next = existing.trimEnd() + '\n' + addition
          await fs.writeFile(target, next, 'utf8')
          logs.push('strengthened .gitignore')
          applied.push({ ...change, content: addition })
        } catch (err) {
          const msg = err instanceof Error ? err.message : String(err)
          errors.push(`.gitignore: ${msg}`)
        }
        continue
      }

      if (!change.content) {
        skipped.push(change)
        continue
      }

      if (ctx.dryRun) {
        logs.push(`[dry-run] would write ${change.path}`)
        applied.push(change)
        continue
      }

      try {
        try {
          await fs.access(target)
          logs.push(`skip ${change.path}: already exists`)
          skipped.push(change)
          continue
        } catch {
          // ok to create
        }
        await fs.mkdir(path.dirname(target), { recursive: true })
        await fs.writeFile(target, change.content, 'utf8')
        logs.push(`wrote ${change.path}`)
        applied.push(change)
      } catch (err) {
        const msg = err instanceof Error ? err.message : String(err)
        errors.push(`${change.path}: ${msg}`)
      }
    }

    return {
      hardenerName: this.name,
      success: errors.length === 0,
      appliedChanges: applied,
      skippedChanges: skipped,
      errors,
      logs,
    }
  }

  async validate(result: ApplyResult, ctx: ApplyContext): Promise<ValidationResult> {
    const errors: string[] = []
    const warnings: string[] = []

    if (!result.success) errors.push(...result.errors)

    for (const change of result.appliedChanges) {
      if (ctx.dryRun) continue
      const target = path.join(ctx.workDir, change.path)
      try {
        const content = await fs.readFile(target, 'utf8')
        if (change.path.includes('dependabot') && !content.includes('package-ecosystem')) {
          errors.push(`${change.path} does not look like a valid Dependabot config`)
        }
        if (change.path === 'SECURITY.md' && content.trim().length < 40) {
          errors.push('SECURITY.md is too short')
        }
        if (change.path === '.gitignore' && !content.includes('.env')) {
          warnings.push('.gitignore may be missing .env patterns')
        }
      } catch {
        if (change.path !== '.gitignore') {
          errors.push(`${change.path} missing after apply`)
        }
      }
    }

    return { ok: errors.length === 0, errors, warnings }
  }
}
