/**
 * TestsHardener — ensures a minimal, runnable test setup exists.
 */

import { promises as fs } from 'node:fs'
import path from 'node:path'
import type {
  Hardener,
  HardenerFindings,
  ChangePlan,
  ApplyContext,
  ApplyResult,
  ValidationResult,
  FileChange,
} from '../types/hardener.js'
import type { ProjectModel } from '../types/project-model.js'

function isNodeProject(model: ProjectModel): boolean {
  return model.packageManagers.some((p) =>
    ['npm', 'pnpm', 'yarn', 'bun'].includes(p)
  ) || model.languages.includes('typescript') || model.languages.includes('javascript')
}

function isPythonProject(model: ProjectModel): boolean {
  return model.languages.includes('python') || model.packageManagers.includes('pip')
}

function buildPytestSmoke(): string {
  return `def test_smoke():
    """Minimal smoke test generated by RepoForge."""
    assert 1 + 1 == 2
`
}

function preferVitest(model: ProjectModel): boolean {
  return (
    model.languages.includes('typescript') ||
    model.testFrameworks.includes('vitest') ||
    model.frameworks.includes('react') ||
    model.frameworks.includes('next')
  )
}

function buildVitestConfig(): string {
  return `import { defineConfig } from 'vitest/config'

export default defineConfig({
  test: {
    globals: true,
    environment: 'node',
    include: ['src/**/*.{test,spec}.{js,ts}', 'tests/**/*.{test,spec}.{js,ts}'],
  },
})
`
}

function buildSmokeTest(_model: ProjectModel): string {
  return `import { describe, it, expect } from 'vitest'

describe('smoke', () => {
  it('runs a basic assertion', () => {
    expect(1 + 1).toBe(2)
  })
})
`
}

function buildJestSmokeTest(): string {
  return `describe('smoke', () => {
  it('runs a basic assertion', () => {
    expect(1 + 1).toBe(2)
  })
})
`
}

export class TestsHardener implements Hardener {
  readonly name = 'tests'
  readonly description =
    'Scaffolds a minimal test setup (vitest/jest/pytest) and a smoke test when no tests exist'

  supports(project: ProjectModel): boolean {
    return isNodeProject(project) || isPythonProject(project)
  }

  async analyze(project: ProjectModel): Promise<HardenerFindings> {
    const missing: string[] = []
    if (!project.hasTests) missing.push('test-files')
    if (
      project.hasTests === false &&
      !project.testFrameworks.includes('vitest') &&
      !project.testFrameworks.includes('jest') &&
      !project.testFrameworks.includes('pytest')
    ) {
      missing.push('test-runner')
    }

    return {
      summary: project.hasTests
        ? `Tests present (${project.testFileCount} files, frameworks: ${project.testFrameworks.join(', ') || 'unknown'})`
        : 'No tests detected — scaffolding recommended',
      details: {
        hasTests: project.hasTests,
        testFileCount: project.testFileCount,
        testFrameworks: project.testFrameworks,
        missing,
        ecosystem: isPythonProject(project) ? 'python' : 'node',
      },
      addressableIssueIds: project.hasTests ? [] : ['no-tests'],
    }
  }

  async plan(project: ProjectModel, findings: HardenerFindings): Promise<ChangePlan> {
    const changes: FileChange[] = []
    const missing = (findings.details.missing as string[]) ?? []

    if (project.hasTests && missing.length === 0) {
      return {
        hardenerName: this.name,
        description: 'Tests already present',
        changes: [],
        risk: 'low',
        requiresConfirmation: false,
      }
    }

    if (isPythonProject(project) && !isNodeProject(project)) {
      changes.push({
        path: 'tests/test_smoke.py',
        content: buildPytestSmoke(),
        reason: 'Add a minimal pytest smoke test',
      })
      return {
        hardenerName: this.name,
        description: 'Scaffold pytest smoke test',
        changes,
        risk: 'low',
        requiresConfirmation: false,
      }
    }

    const useVitest = preferVitest(project)

    if (useVitest) {
      changes.push({
        path: 'vitest.config.ts',
        content: buildVitestConfig(),
        reason: 'Add vitest configuration for a modern, fast test runner',
      })

      changes.push({
        path: project.structure.hasSrcLayout
          ? 'src/smoke.test.ts'
          : 'tests/smoke.test.ts',
        content: buildSmokeTest(project),
        reason: 'Add a minimal smoke test so CI has something to run',
      })
    } else {
      changes.push({
        path: project.structure.hasSrcLayout
          ? 'src/smoke.test.js'
          : 'tests/smoke.test.js',
        content: buildJestSmokeTest(),
        reason: 'Add a minimal Jest-compatible smoke test',
      })
    }

    return {
      hardenerName: this.name,
      description: 'Scaffold minimal test runner configuration and smoke test',
      changes,
      risk: 'low',
      requiresConfirmation: false,
    }
  }

  async apply(ctx: ApplyContext): Promise<ApplyResult> {
    const applied: FileChange[] = []
    const skipped: FileChange[] = []
    const errors: string[] = []
    const logs: string[] = []

    for (const change of ctx.plan.changes) {
      if (!change.content) {
        skipped.push(change)
        continue
      }

      const target = path.join(ctx.workDir, change.path)

      if (ctx.dryRun) {
        logs.push(`[dry-run] would write ${change.path}`)
        applied.push(change)
        continue
      }

      try {
        try {
          await fs.access(target)
          logs.push(`skip ${change.path}: already exists`)
          skipped.push(change)
          continue
        } catch {
          // does not exist
        }

        await fs.mkdir(path.dirname(target), { recursive: true })
        await fs.writeFile(target, change.content, 'utf8')
        logs.push(`wrote ${change.path}`)
        applied.push(change)
      } catch (err) {
        const msg = err instanceof Error ? err.message : String(err)
        errors.push(`${change.path}: ${msg}`)
      }
    }

    if (applied.length > 0) {
      logs.push(
        'note: ensure package.json has "test" script, e.g. "vitest run" or "jest". RepoForge does not auto-edit package.json in v0.1 for safety.'
      )
    }

    return {
      hardenerName: this.name,
      success: errors.length === 0,
      appliedChanges: applied,
      skippedChanges: skipped,
      errors,
      logs,
    }
  }

  async validate(result: ApplyResult, ctx: ApplyContext): Promise<ValidationResult> {
    const errors: string[] = []
    const warnings: string[] = []

    if (!result.success) {
      errors.push(...result.errors)
    }

    for (const change of result.appliedChanges) {
      if (ctx.dryRun) continue
      const target = path.join(ctx.workDir, change.path)
      try {
        const content = await fs.readFile(target, 'utf8')
        if (content.trim().length < 10) {
          errors.push(`${change.path} is empty or too short after write`)
        }
        if (change.path.includes('smoke.test') && !content.includes('expect')) {
          warnings.push(`${change.path} does not contain an expect() call`)
        }
      } catch {
        errors.push(`${change.path} missing after apply`)
      }
    }

    return { ok: errors.length === 0, errors, warnings }
  }
}
