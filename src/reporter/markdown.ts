/**
 * Human-readable Markdown report generator.
 */

import type { RepoForgeReport } from '../types/report.js'

export function renderMarkdownReport(report: RepoForgeReport): string {
  const lines: string[] = []

  lines.push(`# RepoForge Report`)
  lines.push('')
  lines.push(`| Field | Value |`)
  lines.push(`|-------|-------|`)
  lines.push(`| Run ID | \`${report.runId}\` |`)
  lines.push(`| Root | \`${report.rootDir}\` |`)
  lines.push(`| Started | ${report.startedAt} |`)
  lines.push(`| Finished | ${report.finishedAt} |`)
  lines.push(`| Success | ${report.success ? 'yes' : 'no'} |`)
  lines.push(`| Quality (before) | **${report.qualityScoreBefore}/100** |`)
  if (report.qualityScoreAfter != null) {
    lines.push(`| Quality (after) | **${report.qualityScoreAfter}/100** |`)
  }
  lines.push('')
  lines.push(`## Summary`)
  lines.push('')
  lines.push(report.summary)
  lines.push('')

  const m = report.modelBefore
  lines.push(`## Repository snapshot`)
  lines.push('')
  lines.push(`- **Languages:** ${m.languages.join(', ') || '—'}`)
  lines.push(`- **Frameworks:** ${m.frameworks.join(', ') || '—'}`)
  lines.push(`- **Package managers:** ${m.packageManagers.join(', ') || '—'}`)
  lines.push(`- **Tests:** ${m.hasTests ? `yes (${m.testFileCount} files)` : 'no'}`)
  lines.push(`- **CI:** ${m.hasCI ? m.ciProviders.join(', ') : 'no'}`)
  lines.push(`- **Docker:** ${m.hasDocker ? 'yes' : 'no'}`)
  lines.push(`- **Confidence:** ${(m.confidence * 100).toFixed(0)}%`)
  lines.push('')

  if (m.issues.length) {
    lines.push(`## Issues detected`)
    lines.push('')
    for (const issue of m.issues) {
      lines.push(`- **[${issue.severity}]** ${issue.message}${issue.recommendation ? ` — _${issue.recommendation}_` : ''}`)
    }
    lines.push('')
  }

  if (m.security.hasSecretsInCode && m.security.secretsFindings.length) {
    lines.push(`## Possible secrets (paths only)`)
    lines.push('')
    for (const p of m.security.secretsFindings) {
      lines.push(`- \`${p}\``)
    }
    lines.push('')
  }

  lines.push(`## Hardeners`)
  lines.push('')
  for (const h of report.hardeners) {
    const icon =
      h.status === 'applied' ? '✅' :
      h.status === 'planned' ? '🟡' :
      h.status === 'failed' || h.status === 'rolled_back' ? '❌' : '⚪'
    lines.push(`### ${icon} ${h.name} — \`${h.status}\``)
    if (h.findingsSummary) lines.push(`\n${h.findingsSummary}\n`)
    if (h.plan?.changes?.length) {
      lines.push(`Changes:`)
      for (const c of h.plan.changes) {
        lines.push(`- \`${c.path}\` — ${c.reason}`)
      }
      lines.push('')
    }
    if (h.validation?.errors?.length) {
      lines.push(`Errors:`)
      for (const e of h.validation.errors) lines.push(`- ${e}`)
      lines.push('')
    }
    if (h.validation?.warnings?.length) {
      lines.push(`Warnings:`)
      for (const w of h.validation.warnings) lines.push(`- ${w}`)
      lines.push('')
    }
  }

  if (report.diagnostics.length) {
    lines.push(`## Diagnostics`)
    lines.push('')
    for (const d of report.diagnostics) lines.push(`- ${d}`)
    lines.push('')
  }

  if (report.fatalErrors.length) {
    lines.push(`## Fatal errors`)
    lines.push('')
    for (const e of report.fatalErrors) lines.push(`- ${e}`)
    lines.push('')
  }

  lines.push(`---`)
  lines.push(`*Generated by RepoForge*`)
  lines.push('')

  return lines.join('\n')
}
